// scoping-plan kit — the ONE definition of a mockup gallery page (chrome, frame markup, captions).
// Used by capture.mjs (galleries generated from real-product captures) and by plan.mjs when it
// scaffolds a hand-built gallery. build-plan.mjs screenshots every figure.frame of a gallery.
// Installed into <plan>/build/lib/. Change it in the skill's kit/, never in a plan.
import { COLOR, THEME, esc, fontsHref as themeFontsHref } from './common.mjs';

// Frame provenance, recorded on every figure as data-source="<tier>:<what>".
//   capture:<repo>@<sha>        the real product, built at the pinned SHA and driven to the state
//   template:<path or key>      the product's real template (email, PDF) rendered with the example data
//   provider:<what>             a third-party default the product does not own (e.g. Cognito's code email)
//   rebuild:<ui-spec file>      rebuilt from the extracted UI spec — only when the product cannot be built
//   concept:<why>               nothing real exists to render (e.g. an ops command); says why
export const TIERS = ['capture', 'template', 'provider', 'rebuild', 'concept'];
export const sourceTier = (s) => (String(s || '').match(/^([a-z]+):/) || [])[1] || null;

export const GALLERY_CSS = `
  /* ---- Gallery chrome (plan theme, build/lib/gallery.mjs). build-plan screenshots each figure.frame. ---- */
  html, body { margin: 0; background: ${COLOR.page}; color: ${COLOR.textMid}; font-family: "${THEME.font.sans}", sans-serif; }
  .gallery { width: 1440px; margin: 0 auto; padding: 48px 0 96px; display: flex; flex-direction: column; gap: 64px; }
  .intro h1 { margin: 0 0 6px; font-size: 24px; font-weight: 600; color: ${COLOR.textHi}; }
  .intro h1 span { color: ${COLOR.primary}; }
  .intro p { margin: 0; max-width: 1100px; font-size: 14px; line-height: 22px; font-weight: 300; color: ${COLOR.textLow}; }
  figure.frame { margin: 0; width: 1440px; }
  .row { display: flex; gap: 40px; align-items: flex-start; }
  .cell-l { margin: 0 0 10px; font-size: 12px; font-weight: 500; letter-spacing: .06em; text-transform: uppercase; color: ${COLOR.textLow}; }
  figcaption { margin-top: 14px; font-size: 15px; line-height: 22px; color: ${COLOR.textMid}; }
  figcaption b { color: ${COLOR.primary}; font-weight: 600; }
  figcaption span { display: block; margin-top: 2px; font-size: 13px; font-weight: 300; color: ${COLOR.textLow}; }
  /* Device shells: a phone at real point size, a desktop viewport at real width. */
  .phone { width: 390px; height: 844px; border-radius: 48px; overflow: hidden; position: relative; outline: 10px solid #000; box-shadow: 0 0 0 11px ${COLOR.border}; }
  .desktop { width: 1440px; height: 900px; overflow: hidden; border-radius: 6px; outline: 1px solid ${COLOR.border}; }
  .desktop > img, .phone > img { display: block; width: 100%; height: 100%; }
`;

// The caption convention every gallery uses: "<b>S3 · Title.</b> What it shows. <span>Frame s3 · §5 step 2.</span>"
export function caption({ id, title, text = '', section = '' }) {
  return `<b>${esc(id.toUpperCase())} · ${title}.</b> ${text}${section ? `<span>Frame ${esc(id)} · ${section}.</span>` : ''}`;
}

// One frame. body is the screen's HTML (an <img> of a capture, or a hand-built screen).
export function frameHtml({ id, source, body, captionHtml, shell = 'desktop', width, height }) {
  const size = width || height ? ` style="${width ? `width:${width}px;` : ''}${height ? `height:${height}px;` : ''}"` : '';
  const inner = shell === 'none' ? body : `<div class="${shell}"${size}>${body}</div>`;
  return `  <figure class="frame" id="${esc(id)}" data-source="${esc(source)}">
    ${inner}
    <figcaption>${captionHtml}</figcaption>
  </figure>`;
}

// A whole gallery page. frames: already-rendered frameHtml strings. css: extra page CSS (product
// tokens for hand-built screens). generatedBy: set when a script owns the file (it is rewritten).
export function galleryHtml({ name, surface, intro, frames, css = '', head = '', fontsHref = themeFontsHref('mockups/gallery.html'), generatedBy }) {
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
${generatedBy ? `<!-- GENERATED by ${generatedBy} — edit that script and re-run it; never edit this file. -->\n` : ''}<title>${esc(name)} · ${esc(surface)} · mockups</title>
<link rel="stylesheet" href="${fontsHref}">
<style>${GALLERY_CSS}</style>
${css ? `<style>\n${css}\n</style>\n` : ''}${head}</head>
<body>
<main class="gallery">
  <header class="intro">
    <h1>${esc(name)} · <span>${esc(surface)}</span></h1>
    <p>${intro}</p>
  </header>

${frames.join('\n\n')}
</main>
</body>
</html>
`;
}
