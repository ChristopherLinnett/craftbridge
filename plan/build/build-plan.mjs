// A value inside a CSS string literal: CSS does not decode HTML entities, so escape for CSS instead.
const cssString = (v) => String(v).replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/</g, '\\3c ').replace(/\n/g, '\\a ');

