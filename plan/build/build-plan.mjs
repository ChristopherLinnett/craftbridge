// ---------------------------------------------------------------- 1. generated blocks
let md = fs.readFileSync(MASTER, 'utf8').replace(
  /(<!-- @gen (\S+)(?: ([^>]*?))? -->)[\s\S]*?(<!-- @end-gen -->)/g,
  (_, open, name, args, close) => {
    const gen = cfg.generators[name];
    if (!gen) throw new Error(`@gen ${name}: no generator "${name}" in plan.config.mjs generators`);
    return `${open}\n${gen((args || '').trim(), { read, root: ROOT })}\n${close}`;
  },
);
fs.writeFileSync(MASTER, md);

// ---------------------------------------------------------------- 2. mockup screenshots
function galleryStale(m) {
  const page = path.join(ROOT, m.file);
  const html = fs.readFileSync(page, 'utf8');
  const ids = [...html.matchAll(/<figure class="frame"[^>]*\bid="([^"]+)"/g)].map((x) => x[1]);
  const t = fs.statSync(page).mtimeMs;
  return !ids.length || ids.some((id) => {
    const p = path.join(SHOTS_DIR, `${id}.png`);
    return !fs.existsSync(p) || fs.statSync(p).mtimeMs < t;
  });
}
async function shootMockups(force) {
  const todo = cfg.mockups.filter((m) => force || galleryStale(m));
  if (!todo.length) return;
  const b = await browser();
  fs.mkdirSync(SHOTS_DIR, { recursive: true });
  for (const m of todo) {
    const page = await b.newPage();
    await page.setViewport({ width: m.viewport?.width || 1600, height: m.viewport?.height || 1000, deviceScaleFactor: m.deviceScale || 1 });
    await page.goto('file://' + path.join(ROOT, m.file), { waitUntil: 'networkidle0', timeout: 120000 });
    if (m.shotCss) await page.addStyleTag({ content: m.shotCss });
    await page.evaluate(() => document.fonts.ready);
    // Galleries that render asynchronously set <html data-ready="1"> when every frame is drawn.
    if (m.waitReady) await page.waitForFunction(() => document.documentElement.dataset.ready === '1', { timeout: 120000 });
    await sleep(m.settleMs ?? 2000);
    const frames = await page.$$eval('figure.frame', (els) => els.map((el) => {
      const f = el.getBoundingClientRect();
      const cap = el.querySelector('figcaption');
      const bottom = cap ? cap.getBoundingClientRect().top : f.bottom;
      return { id: el.id, x: f.left + window.scrollX, y: f.top + window.scrollY, w: f.width, h: bottom - f.top };
    }));
    for (const fr of frames) {
      if (!fr.id.startsWith(m.prefix)) warnings.push(`${m.file}: frame "${fr.id}" does not start with its prefix "${m.prefix}"`);
      await page.screenshot({ path: path.join(SHOTS_DIR, `${fr.id}.png`), clip: { x: fr.x, y: fr.y, width: fr.w, height: Math.max(40, fr.h) }, captureBeyondViewport: true });
      console.log(`shot ${fr.id}: ${Math.round(fr.w)}×${Math.round(fr.h)}`);
    }
    await page.close();
  }
  await b.close();
}
if (!process.argv.includes('--no-shots') && cfg.mockups.length) await shootMockups(process.argv.includes('--shots'));

// ---------------------------------------------------------------- 3. views
const GEN_NOTE = (file) => `<!-- GENERATED from ${cfg.master} by build/build-plan.mjs — do not edit this file. -->\n> **Generated view** of the plan of record [\`${cfg.master}\`](${relLink(file, cfg.master)}) (rendered: [\`${path.basename(cfg.html)}\`](${relLink(file, cfg.html)})). Edit the master, then run \`node build/build-plan.mjs\`.\n`;
function rebaseLinks(text, fromFile) {
  const depth = fromFile.split('/').length - 1;
  if (!depth) return text;
  return text.replace(/\]\((?!https?:|#|mailto:|\/)(\.\/)?([^)]+)\)/g, (_, _dot, p) => `](${'../'.repeat(depth)}${p})`);
}
const views = new Map();
for (const m of md.matchAll(/<!-- @view ([^>]+?) -->\n([\s\S]*?)<!-- @end -->/g)) {
  // Title the chunk with the nearest preceding heading so a view reads standalone.
  const before = md.slice(0, m.index);
  const heading = [...before.matchAll(/^(#{2,3}) (.+)$/gm)].pop();
  for (const file of m[1].split(/\s+/)) {
    if (!views.has(file)) views.set(file, []);
    const chunk = m[2].trimStart().startsWith('#') ? m[2] : `${heading ? `## ${heading[2]}\n\n` : ''}${m[2]}`;
    views.get(file).push(chunk.trim());
  }
}
for (const [file, chunks] of views) {
  const title = `# ${cfg.name} — ${path.basename(file, '.md').replace(/[-_]/g, ' ').toUpperCase()}`;
  const body = rebaseLinks(chunks.join('\n\n---\n\n'), file)
    .replace(/<!-- @(?:gen|end-gen|code)[^>]*-->\n?/g, '');
  fs.mkdirSync(path.join(ROOT, path.dirname(file)), { recursive: true });
  fs.writeFileSync(path.join(ROOT, file), `${title}\n\n${GEN_NOTE(file)}\n${body}\n`);
  console.log(`view ${file}: ${chunks.length} section(s)`);
}
for (const m of md.matchAll(/<!-- @code (\S+) -->\n```\w*\n([\s\S]*?)```/g)) {
  fs.mkdirSync(path.join(ROOT, path.dirname(m[1])), { recursive: true });
  fs.writeFileSync(path.join(ROOT, m[1]), m[2]);
  console.log(`code ${m[1]}`);
}

