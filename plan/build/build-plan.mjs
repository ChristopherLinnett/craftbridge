const PART = cfg.partPattern || /^Part [A-Z] — /;
marked.use({
  renderer: {
    heading({ tokens, depth }) {
      const html = this.parser.parseInline(tokens);
      let id = slug(html) || 'section';
      while (used.has(id)) id += '-x';
      used.add(id);
      if (depth <= 2) toc.push({ depth, id, text: html.replace(/<[^>]+>/g, '') });
      const cls = depth === 1 ? (toc.filter((t) => t.depth === 1).length === 1 ? ' class="doc-title"' : ' class="part"') : '';
      return `<h${depth} id="${id}"${cls}>${html}<a class="anchor" href="#${id}" aria-label="link">#</a></h${depth}>\n`;
    },
    table(token) {
      const html = marked.Renderer.prototype.table.call(this, token);
      return `<div class="table-wrap">${html}</div>`;
    },
    // A path may break after each "/", so a table cell wraps it at a directory, never mid-name.
    codespan({ text }) {
      const esc = text.replace(/&(?!(?:[a-z]+|#\d+);)/gi, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
      return `<code>${esc.replace(/\//g, '/<wbr>')}</code>`;
    },
  },
});
let body = marked.parse(src);
