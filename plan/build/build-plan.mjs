// Builds everything derived from the master plan (config.master):
//   1. expands generated blocks   <!-- @gen <name> <args> --> … <!-- @end-gen -->   (config.generators)
//   2. screenshots every mockup frame (figure.frame[id]) → mockups/shots/<id>.png
//      (only galleries whose shots are missing or older than the page; --shots forces, --no-shots skips)
//   3. writes the per-team VIEW files from <!-- @view a.md b.md --> … <!-- @end --> blocks
//      and code files from <!-- @code path --> + the fenced block after it
//   4. renders config.html: themed, sidebar TOC, draw.io SVGs inlined where the markdown
//      carries a ```mermaid block tagged `%% @drawio <id> | <caption>`, mockup shots and
//      images as zoomable figures.
// Usage: node build/build-plan.mjs [--no-shots | --shots]      (run build-diagrams.mjs first)
// Installed by scoping-plan — change it in the skill's kit/, never in a plan.
