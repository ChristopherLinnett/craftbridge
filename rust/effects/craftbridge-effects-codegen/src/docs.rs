//! The command reference the docs carry: every command of a surface with its keys and their types, as
//! one section per namespace, written to `commands.md` for `docs/generated/`. `cargo xtask generate`
//! runs it through xtask, which hands it the surface file the `surface` command writes — the file is
//! read by [`Surface::parse`], the surface's one reader, so the reference, the two facades and the diff
//! describe the same commands the one way, and no second reader can drift from any of them.
//!
//! The text is written to change as little as possible when the surface moves: commands and namespaces
//! in id order, one line per key, nothing dated and nothing the machine differs on. A pin move that
//! adds a command is then a diff that reads as exactly that.

use crate::model::{Command, Key, Surface};

/// The subcommand that runs this emitter, named in the notice header and the usage line.
pub(crate) const COMMAND: &str = "docs";

/// The file this emitter writes into the output folder.
pub(crate) const FILE: &str = "commands.md";

/// Render the reference for `surface`. Deterministic by construction: the same surface always renders
/// to the same bytes, which the generated-file check relies on.
pub(crate) fn render(surface: &Surface) -> String {
    let mut text = String::new();
    text.push_str("<!-- @generated by `cargo xtask generate` (craftbridge-effects-codegen docs): do not edit by hand. -->\n\n");
    text.push_str("# Engine commands\n\n");
    text.push_str(&format!(
        "Every command of the EffectCraft engine at the pinned revision — {} of them — with every key it takes and the type of each, read from `api-surface.json`: engine version `{}`, EffectCraft at `{}`.\n\n",
        surface.commands.len(),
        surface.engine_version,
        surface.pin,
    ));
    text.push_str(
        "The Swift and Kotlin facades are generated from the same surface, so each command below is what the facade method of the same name sends. The line after a command's title is the engine's own description of what it takes. A key is required when a call that leaves it out is refused before the command runs; `enum` types list the words they accept after a colon. A command marked *refused* or *withheld* is one no app can call: the confined engine, or the plugin's own door before it, answers every call of it with that refusal, so no facade method sends it.\n\n",
    );
    for (namespace, commands) in namespaces(surface) {
        let counted = if commands.len() == 1 { "1 command.".to_string() } else { format!("{} commands.", commands.len()) };
        text.push_str(&format!("## {namespace}\n\n{counted}\n\n"));
        for command in commands {
            render_command(&mut text, command);
        }
    }
    text
}

/// The commands in id order, grouped by the part of the id before the first dot — the namespace the
/// facades are cut by — each group in namespace order.
fn namespaces(surface: &Surface) -> Vec<(String, Vec<&Command>)> {
    let mut commands: Vec<&Command> = surface.commands.iter().collect();
    commands.sort_by_key(|command| command.id.as_str());
    let mut groups: std::collections::BTreeMap<&str, Vec<&Command>> = std::collections::BTreeMap::new();
    for command in commands {
        let namespace = command.id.split('.').next().map_or(command.id.as_str(), |part| part);
        groups.entry(namespace).or_default().push(command);
    }
    groups.into_iter().map(|(namespace, commands)| (namespace.to_string(), commands)).collect()
}

/// One command: its title line, the engine's own parameter line, why an app cannot call it when it
/// cannot, and one table row per key.
fn render_command(text: &mut String, command: &Command) {
    text.push_str(&format!("### `{}` — {}\n\n", command.id, escape(&command.label)));
    if !command.params.is_empty() {
        text.push_str(&format!("{}\n\n", code_span(&command.params)));
    }
    if command.withheld_by_plugin {
        text.push_str("*Withheld by the plugin: every call is answered with its refusal.*\n\n");
    } else if command.refused_under_confinement {
        text.push_str("*Refused under confinement: every call is answered with its refusal.*\n\n");
    }
    if command.keys.is_empty() {
        text.push_str("Takes no keys.\n\n");
        return;
    }
    text.push_str("| key | type | required | what it is |\n|---|---|---|---|\n");
    for key in &command.keys {
        text.push_str(&format!("| `{}` | {} | {} | {} |\n", key.name, key_type(key), if key.required { "yes" } else { "no" }, escape(&key.doc),));
    }
    text.push('\n');
}

/// The key's type as the reference shows it: the surface's type name, and an `enum`'s words after it.
fn key_type(key: &Key) -> String {
    match &key.values {
        Some(values) if !values.is_empty() && key.key_type == "enum" => format!("`enum`: {}", values.iter().map(String::as_str).collect::<Vec<_>>().join(", ")),
        _ => format!("`{}`", key.key_type),
    }
}

/// Text that came from the engine as one code span on one line. A code span reads no escapes, so its text is
/// written as it is, between runs of one backquote more than the longest run it holds, which no backquote
/// inside can end, and spaced from them when it starts or ends with one, which Markdown strips again.
fn code_span(text: &str) -> String {
    let text = text.replace('\n', " ");
    let longest = text.split(|character| character != '`').map(str::len).max().unwrap_or(0);
    let fence = "`".repeat(longest + 1);
    let pad = if text.starts_with('`') || text.ends_with('`') { " " } else { "" };
    format!("{fence}{pad}{text}{pad}{fence}")
}

/// Text that came from the engine, made safe for a table cell or a title: no cell break, no line break.
fn escape(text: &str) -> String {
    text.replace('\\', "\\\\").replace('|', "\\|").replace('\n', " ")
}

#[cfg(test)]
mod tests {
    use super::*;

    fn fixture() -> Surface {
        Surface::parse(
            r#"{
              "app": "effectcraft",
              "engineVersion": "1.2.3",
              "pin": "0123456789abcdef0123456789abcdef01234567",
              "commands": [
                {"id": "text.fonts", "label": "List fonts", "params": "query?", "journal": false,
                 "keys": [{"name": "query", "required": false, "type": "string", "doc": "keep faces whose family name contains this"}]},
                {"id": "essential.addText", "label": "Add text", "params": "comp, text", "journal": true, "refusedUnderConfinement": true,
                 "keys": [
                   {"name": "comp", "required": true, "type": "item", "doc": "the comp | receiving the text"},
                   {"name": "align", "required": false, "type": "enum", "values": ["left", "right"], "doc": ""}
                 ]},
                {"id": "render.add", "label": "Add to queue", "params": "", "journal": true, "withheldByPlugin": true, "keys": []}
              ],
              "tools": []
            }"#,
        )
        .unwrap()
    }

    #[test]
    fn the_notice_opens_the_file_and_names_its_generator() {
        let text = render(&fixture());
        assert_eq!(text.lines().next().unwrap(), "<!-- @generated by `cargo xtask generate` (craftbridge-effects-codegen docs): do not edit by hand. -->");
    }

    #[test]
    fn namespaces_come_in_order_with_their_commands_in_id_order() {
        let text = render(&fixture());
        let marks: Vec<usize> = ["## essential", "## render", "## text"].iter().map(|mark| text.find(mark).unwrap()).collect();
        assert!(marks.windows(2).all(|pair| pair[0] < pair[1]), "{marks:?}");
        assert!(text.contains("### `essential.addText` — Add text"), "{text}");
        assert!(text.contains("## text\n\n1 command."), "{text}");
    }

    #[test]
    fn keys_show_their_type_requiredness_and_words_of_an_enum() {
        let text = render(&fixture());
        assert!(text.contains("| `comp` | `item` | yes | the comp \\| receiving the text |"), "{text}");
        assert!(text.contains("| `align` | `enum`: left, right | no |  |"), "{text}");
        assert!(text.contains("Takes no keys."), "{text}");
    }

    #[test]
    fn a_command_no_app_can_call_is_marked() {
        let text = render(&fixture());
        assert!(text.contains("*Refused under confinement: every call is answered with its refusal.*"), "{text}");
        assert!(text.contains("*Withheld by the plugin: every call is answered with its refusal.*"), "{text}");
    }

    /// The engine's parameter line is shown as it reads: its `|` and `\\` never take an escape, which a code
    /// span would show, and a backquote inside it never ends the span.
    #[test]
    fn the_parameter_line_is_one_code_span_whatever_it_holds() {
        assert_eq!(code_span("query?"), "`query?`");
        assert_eq!(code_span("{kind: a|b, path: C:\\x}"), "`{kind: a|b, path: C:\\x}`");
        assert_eq!(code_span("{command} → JSON `schema`"), "`` {command} → JSON `schema` ``");
        assert_eq!(code_span("``a``\nb"), "``` ``a`` b ```");
        let surface = Surface::parse(
            r#"{"app": "effectcraft", "engineVersion": "1.2.3", "pin": "0123456789abcdef0123456789abcdef01234567", "tools": [],
                "commands": [{"id": "meta.describe", "label": "Describe", "params": "{kind: a|b} → JSON `schema`", "journal": false, "keys": []}]}"#,
        )
        .unwrap();
        assert!(render(&surface).contains("\n`` {kind: a|b} → JSON `schema` ``\n"), "{}", render(&surface));
    }

    #[test]
    fn the_same_surface_renders_the_same_bytes() {
        assert_eq!(render(&fixture()), render(&fixture()));
    }
}
